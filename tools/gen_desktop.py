#!/usr/bin/env python3
"""Generates the desktop plugin's tables (desktop/gen/): VADER as a VST3 / VST2 for Windows and Linux.

    python3 tools/gen_desktop.py

It reads the same two sources the Force build uses, so the two never drift apart:
  tools/gen_params.py   every parameter (key, range, options)  ->  desktop/gen/vader_gen.h  (the host's parameter list)
  tools/vader_skin.py   where every control sits on the six pages (1280 x 628 space)  ->  the same header (the window)
and embeds what the window and the first run need:  art/fonts/*.ttf, shapes/*  ->  desktop/gen/vader_res.cpp.

What the host sees: the global settings first (PRESET, TIMBRE, CORNER ... so a host that restores parameters in order
selects the timbre before it writes that timbre's sound), then the sound, then the five momentary buttons. The main
page's five corner knobs (f_*) are NOT host parameters: they edit the selected corner, which the host would see as
four sets of parameters anyway (a_og1 ... d_reso), so the window writes those instead. The screen's own data (tiles,
trail, QR, ...) is not exposed at all: the window draws it from the engine's live view.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import gen_params as G  # noqa: E402
import vader_skin as V  # noqa: E402

OUT = os.path.join(ROOT, "desktop", "gen")
TAB_H = 40                      # the tab row above the 1280 x 628 pages
CANVAS_W, CANVAS_H = V.W, V.H + TAB_H
K = dict(HLINE=0, TOGGLE=1, BUTTON=2, RADIO=3, POPUP=4, FIELD=5, FADER=6, TITLE=7, TEXT=8, METER=9, ENVWIN=10,
         SCREEN=11, READOUT=12, PRESETS=13, LIVETEXT=14)
SKIP_KEYS = {"web_url", "qr_show"}           # the phone's address and the logo/QR switch: nothing to show on a desktop
HIDDEN_KEYS = {"qr_show", "motion"}          # not host parameters (motion stays on)


def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    params, rows, snd_slots, glob_slots = G.build()
    byname = {p["key"]: p for p in params}
    rowof = {r[0]: r for r in rows}
    # ---- the host's parameters, in the order a restore wants
    glob = [r for r in rows if r[1] == "GLOB" and r[0] not in HIDDEN_KEYS]
    first = ["preset", "timbre", "corner"]
    glob = [rowof[k] for k in first] + [r for r in glob if r[0] not in first]
    snd = [r for r in rows if r[1] == "SND"]
    trg = [r for r in rows if r[1] == "TRIG"]
    exp = glob + snd + trg
    eng_index = {r[0]: i for i, r in enumerate(rows)}
    exp_index = {r[0]: i for i, r in enumerate(exp)}
    L = ["// GENERATED by tools/gen_desktop.py: do not edit. VADER desktop: the host's parameters and the window's pages.",
         "#pragma once", "#include <stdint.h>", "#define VG_NEXP %d" % len(exp), "#define VG_NENG %d" % len(rows),
         "#define VG_CANVAS_W %d" % CANVAS_W, "#define VG_CANVAS_H %d" % CANVAS_H, "#define VG_TAB_H %d" % TAB_H,
         "enum { VG_GLOB, VG_SND, VG_TRIG };"]
    # option lists
    seen = {}
    for r in exp:
        if r[8]:
            t = tuple(r[8])
            if t not in seen:
                seen[t] = "VG_OPT%d" % len(seen)
                L.append("static const char *const %s[] = {%s};" % (seen[t], ", ".join(cstr(o) for o in t)))
    L.append("typedef struct { const char *key, *name; uint8_t kind, nopts, isint; int16_t eng; float def, mn, mx; "
             "const char *const *opts; } VgPar;")
    L.append("static const VgPar VG_PARS[VG_NEXP] = {")
    for r in exp:
        key, kind, slot, lo, hi, d, nopts, isint, opts = r
        if nopts:
            lo, hi = 0, nopts - 1
        L.append("    {%s, %s, VG_%s, %d, %d, %d, %s, %s, %s, %s}," % (
            cstr(key), cstr(byname[key]["name"]), {"GLOB": "GLOB", "SND": "SND", "TRIG": "TRIG"}[kind], nopts, isint,
            eng_index[key], G.cf(d), G.cf(lo), G.cf(hi), seen[tuple(opts)] if opts else "0"))
    L.append("};")
    L.append("enum { " + ", ".join("VGP_%s" % G.c_name(r[0]) for r in exp) + " };")
    # engine index -> host index (-1: not a host parameter)
    m = [exp_index.get(r[0], -1) for r in rows]
    L.append("static const int16_t VG_ENG2EXP[VG_NENG] = {%s};" % ", ".join(map(str, m)))
    # the corner knobs: which host parameter holds field f of corner c, and the five main-page knobs' fields
    cf = [c[0] for c in G.CORNER]
    L.append("#define VG_NCF %d" % len(cf))
    L.append("static const int16_t VG_CORNER_PAR[4][VG_NCF] = {")
    for c in "abcd":
        L.append("    {%s}," % ", ".join(str(exp_index["%s_%s" % (c, f)]) for f in cf))
    L.append("};")
    L.append("static const uint8_t VG_FRONT_FIELD[5] = {%s};" % ", ".join(str(cf.index(f)) for f, _ in G.FRONT))
    L.append("static const char *const VG_FRONT_NAME[5] = {%s};" % ", ".join(cstr(n) for _, n in G.FRONT))
    L.append("static const char *const VG_CORNER_NAME[5] = {\"A\", \"B\", \"C\", \"D\", \"ALL\"};")

    L.append("#define VG_NENG %d" % len(G.ENGINE_TAB))
    L.append("static const char *const VG_ENG_KNOBS[VG_NENG][4] = {%s};" % ", ".join(
        "{" + ", ".join(cstr(n) for n in e[3]) + "}" for e in G.ENGINE_TAB))
    L.append("#define VG_NMODES %d" % len(G.SIM_MODES))
    L.append("static const char *const VG_MODE_KNOBS[VG_NMODES][8] = {%s};" % ", ".join(
        "{" + ", ".join(cstr(n) for n in row) + "}" for row in G.MODE_KNOBS))
    # ---- the pages
    L.append("enum { %s };" % ", ".join("VGK_%s = %d" % (k, v) for k, v in K.items()))
    L.append("typedef struct {\n    uint8_t kind, big, vertical, cols, size, nlab;\n    int16_t par, front, aux, x, y, w, h, ow, oh, lx, ly, wpar, wopt;\n"
             "    const char *label;\n    const char *const *labels;\n    const uint8_t *order;\n    uint32_t colour;\n} VgCtl;")
    uid = [0]

    def ctl(c, dy):
        k = c["kind"]
        key = c.get("key")
        if k == "qr":
            return None
        if k == "livetext":
            return dict(kind=K["LIVETEXT"], big=0, vertical=0, cols=0, size=22, nlab=0, par=-1, front=0, aux=200 if key == "cpu" else int(key[2:]) + (100 if key.startswith("cn") else 0),
                        x=c["x"], y=c["y"] + dy, w=c["w"], h=28, ow=0, oh=0, lx=0, ly=0, wpar=-1, wopt=0, label="",
                        labels=None, order=None, colour=0xFFFFFF)
        if key in SKIP_KEYS or c.get("text") == "COMPANION SCREEN":
            return None
        e = dict(kind=K[k.upper()] if k.upper() in K else None, big=int(bool(c.get("big"))), vertical=0, cols=0,
                 size=0, nlab=0, par=-1, front=0, aux=0, x=c.get("x", 0), y=c.get("y", 0) + dy, w=c.get("w") or 0, h=c.get("h") or 0,
                 ow=0, oh=0, lx=0, ly=0, wpar=-1, wopt=0, label="", labels=None, order=None, colour=0xFFFFFF)
        if k == "readout":
            e["kind"] = K["READOUT"]
            return e
        if k == "screen":
            return e
        if k == "hline":
            e["h"] = V.HLB if c.get("big") else V.HL
        if k == "envwin":
            e["kind"] = K["ENVWIN"]
            e["x"], e["y"], e["w"], e["h"] = V.ENV_BOX[0], V.ENV_BOX[1] + dy, V.ENV_BOX[2], V.ENV_BOX[3]
            return e
        if k == "meter":
            e["aux"] = int(key[-1])
            e["h"] = 28
            e["label"] = c.get("label") or ""
            return e
        if k == "text":
            e["label"] = c["text"]
            e["size"] = c.get("size", 18)
            col = c.get("colour", V.INK_DIM)
            e["colour"] = (col[0] << 16) | (col[1] << 8) | col[2]
            return e
        if k == "title":
            e["label"] = c["text"]
            return e
        # controls on a parameter
        if key and key.startswith("f_"):
            e["front"] = [f for f, _ in G.FRONT].index(key[2:]) + 1
        elif key:
            if key not in exp_index:
                return None
            e["par"] = exp_index[key]
        lab = c.get("label") or c.get("caption")
        if k == "field" or k == "popup":
            e["label"] = c.get("caption") or ""
        else:
            e["label"] = lab or byname[key]["name"]
        if k == "radio":
            opts = byname[key].get("options") or []
            labels = c.get("labels") or opts
            e["nlab"] = len(labels)
            e["labels"] = labels
            order = c.get("order") or list(range(len(opts)))
            e["order"] = order
            e["vertical"] = int(bool(c.get("vertical")))
            e["cols"] = c.get("cols") or 0
        if k == "popup":
            la = c.get("list_at") or (c["x"], c["y"] + c["h"] + 4)
            e["lx"], e["ly"] = la[0], la[1] + dy
            e["cols"], e["ow"], e["oh"] = c.get("cols", 2), c.get("ow", 150), c.get("oh", 40)
        if k == "fader":
            e["h"] = 186
        wh = c.get("when")
        if wh:
            wk, wo = wh.split(":")
            e["wpar"] = exp_index[wk]
            e["wopt"] = (byname[wk].get("options") or []).index(wo)
        return e

    def emit_page(name, comps):
        out = []
        for c in comps:
            e = ctl(c, TAB_H)
            if e is not None:
                out.append(e)
        arrs = []
        for i, e in enumerate(out):
            if e["labels"]:
                L.append("static const char *const VG_%s_L%d[] = {%s};" % (name, i, ", ".join(cstr(s) for s in e["labels"])))
                L.append("static const uint8_t VG_%s_O%d[] = {%s};" % (name, i, ", ".join(map(str, e["order"]))))
        L.append("static const VgCtl VG_%s[] = {" % name)
        for i, e in enumerate(out):
            lab = "VG_%s_L%d" % (name, i) if e["labels"] else "0"
            od = "VG_%s_O%d" % (name, i) if e["labels"] else "0"
            L.append("    {%d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %s, %s, %s, 0x%06X}," % (
                e["kind"], e["big"], e["vertical"], e["cols"], e["size"], e["nlab"], e["par"], e["front"], e["aux"], e["x"],
                e["y"], e["w"], e["h"], e["ow"], e["oh"], e["lx"], e["ly"], e["wpar"], e["wopt"], cstr(e["label"]), lab, od,
                e["colour"]))
        L.append("};")
        L.append("#define VG_%s_N %d" % (name, len(out)))
        return len(out)

    names = []
    for tab, fn in zip(V.TABS, V.PAGES):
        comps, _q = fn()
        if tab == "MAIN":   # the companion screen's QR code makes room for the live screen
            comps = list(comps) + [{"kind": "screen", "x": 436, "y": 118, "w": 408, "h": 274}]
        emit_page(tab, comps)
        names.append(tab)
    # a page for the screen alone, big, with the orbit's controls beside it
    R = 872
    sc = [{"kind": "screen", "x": 16, "y": 70, "w": 840, "h": 552},
          V.popup("shape", R, 68, 392, "SHAPE", h=44, list_at=(R - 330, 118), cols=4, ow=158, oh=44),
          V.hl("orb_speed", R, 124, 192, "ORBIT SPEED"), V.hl("orb_size", R + 200, 124, 192, "ORBIT SIZE"),
          V.hl("sub_size", R, 180, 192, "SUBORBIT SIZE"), V.hl("sub_speed", R + 200, 180, 192, "SUBORBIT SPEED"),
          V.hl("rotate", R, 236, 192, "ROTATE"), V.hl("orb_env", R + 200, 236, 192, "ORBIT ENV"),
          V.hl("spin", R, 292, 192, "3D SPIN"), V.hl("tilt", R + 200, 292, 192, "3D TILT"),
          V.title("CORNER SELECT", R, 356, 392), V.radio("corner", R, 378, 392, h=38),
          V.hl("f_og1", R, 428, 192, "GEN 1"), V.hl("f_og2", R + 200, 428, 192, "GEN 2"),
          V.hl("f_blend", R, 484, 192, "BLEND"), V.hl("f_cutoff", R + 200, 484, 192, "CUTOFF"),
          V.hl("f_reso", R, 540, 192, "RESO"),
          V.tog("arp_on", R + 200, 546, 192, "ARP", h=44)]
    emit_page("SCREENPG", sc)
    names.append("SCREEN")
    L.append("#define VG_NPAGES %d" % len(names))
    L.append("static const char *const VG_PAGE_NAME[VG_NPAGES] = {%s};" % ", ".join(cstr(n) for n in names))
    L.append("static const VgCtl *const VG_PAGE[VG_NPAGES] = {%s};" % ", ".join(
        "VG_%s" % ("SCREENPG" if n == "SCREEN" else n) for n in names))
    L.append("static const int VG_PAGE_N[VG_NPAGES] = {%s};" % ", ".join(
        "VG_%s_N" % ("SCREENPG" if n == "SCREEN" else n) for n in names))
    # the strip across every page
    stripe = []
    for c in V.stripe():
        e = ctl(c, TAB_H)
        if e:
            stripe.append(c)
    emit_page("STRIPE", stripe)
    # which engine keys the window reads for text (dynamic display)
    L.append("static const int16_t VG_TEXT_PARS[] = {%s};" % ", ".join(
        str(exp_index[k]) for k in ("file", "user_slot", "preset", "shape")))
    os.makedirs(OUT, exist_ok=True)
    open(os.path.join(OUT, "vader_gen.h"), "w").write("\n".join(L) + "\n")

    # ---- embedded resources: the two fonts, the shapes of a first run
    R_ = ["// GENERATED by tools/gen_desktop.py: do not edit. Fonts (Chakra Petch, SIL OFL) and the example shapes.",
          '#include "vader_res.h"']

    def blob(name, path):
        d = open(path, "rb").read()
        R_.append("static const unsigned char %s[] = {" % name)
        for i in range(0, len(d), 24):
            R_.append(",".join(str(b) for b in d[i:i + 24]) + ",")
        R_.append("0};")
        return len(d)

    nb = blob("RES_FONT_BOLD", os.path.join(ROOT, "art", "fonts", "ChakraPetch-Bold.ttf"))
    ns = blob("RES_FONT_SEMI", os.path.join(ROOT, "art", "fonts", "ChakraPetch-SemiBold.ttf"))
    files = sorted(f for f in os.listdir(os.path.join(ROOT, "shapes")) if not f.startswith("."))
    for i, f in enumerate(files):
        blob("RES_SHAPE_%d" % i, os.path.join(ROOT, "shapes", f))
    R_.append("const unsigned char *vg_font_bold(int *n) { *n = %d; return RES_FONT_BOLD; }" % nb)
    R_.append("const unsigned char *vg_font_semi(int *n) { *n = %d; return RES_FONT_SEMI; }" % ns)
    R_.append("int vg_shape_count(void) { return %d; }" % len(files))
    R_.append("const char *vg_shape_name(int i) {\n    static const char *const N[] = {%s};\n    return N[i];\n}" % ", ".join(cstr(f) for f in files))
    sizes = [os.path.getsize(os.path.join(ROOT, "shapes", f)) for f in files]
    R_.append("const unsigned char *vg_shape_data(int i, int *n) {\n    static const unsigned char *const D[] = {%s};\n    static const int S[] = {%s};\n    *n = S[i];\n    return D[i];\n}" % (
        ", ".join("RES_SHAPE_%d" % i for i in range(len(files))), ", ".join(map(str, sizes))))
    open(os.path.join(OUT, "vader_res.cpp"), "w").write("\n".join(R_) + "\n")
    open(os.path.join(OUT, "vader_res.h"), "w").write(
        "// GENERATED by tools/gen_desktop.py\n#pragma once\n"
        "const unsigned char *vg_font_bold(int *n);\nconst unsigned char *vg_font_semi(int *n);\n"
        "int vg_shape_count(void);\nconst char *vg_shape_name(int i);\nconst unsigned char *vg_shape_data(int i, int *n);\n")
    print("gen_desktop: %d host parameters, %d pages, %d shapes embedded" % (len(exp), len(names), len(files)))


if __name__ == "__main__":
    main()
