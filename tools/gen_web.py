#!/usr/bin/env python3
"""The companion screen's files as C arrays (build/web_assets.h): web/index.html, and the icon (art/logo.png when it
exists, else the VADER mark drawn by tools/vader_skin.py) as a 192 px PNG.

    python3 tools/gen_web.py
"""
import io
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))


def c_array(name, data, as_string):
    if as_string:
        out = ['static const char %s[] =' % name]
        s = data.decode("utf-8")
        for line in s.split("\n"):
            esc = line.replace("\\", "\\\\").replace('"', '\\"').replace("?", "\\?")
            out.append('    "%s\\n"' % esc)
        out[-1] += ";"
        return "\n".join(out) + "\n"
    out = ["static const unsigned char %s[%d] = {" % (name, len(data))]
    for i in range(0, len(data), 24):
        out.append("    " + ", ".join("%d" % b for b in data[i:i + 24]) + ",")
    out.append("};")
    return "\n".join(out) + "\n"


def main():
    html = open(os.path.join(ROOT, "web", "index.html"), "rb").read()
    import vader_skin
    icon = vader_skin.vader_mark(192)
    buf = io.BytesIO()
    icon.save(buf, "PNG", optimize=True)
    os.makedirs(os.path.join(ROOT, "build"), exist_ok=True)
    with open(os.path.join(ROOT, "build", "web_assets.h"), "w") as f:
        f.write("/* GENERATED by tools/gen_web.py: the companion screen's page and icon */\n#pragma once\n")
        f.write(c_array("WEB_INDEX_HTML", html, True))
        f.write(c_array("WEB_ICON_PNG", buf.getvalue(), False))
    print("gen_web: page %d bytes, icon %d bytes" % (len(html), len(buf.getvalue())))


if __name__ == "__main__":
    main()
